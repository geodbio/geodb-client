#!/usr/bin/env python3
"""Rewrite the README's generated regions from the client's registries — so
the README cannot list a method, path, export model or dataset reason code the
client does not have:

* ``tables``   — from ``geodb.client.TABLES`` (the records-lane table);
* ``datasets`` — from ``geodb.errors.DATASET_REASON_CODES`` +
  ``RECORDS_REASON_CODES`` and what ``geodb.datasets`` re-sends (the dataset
  reason-code table).

    python scripts/gen_readme.py           # rewrite the marked regions
    python scripts/gen_readme.py --check   # exit 1 when one is stale
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
README = ROOT / "README.md"
BEGIN = "<!-- BEGIN:tables (generated by scripts/gen_readme.py from geodb.client.TABLES) -->"
END = "<!-- END:tables -->"
DATASETS_BEGIN = ("<!-- BEGIN:datasets (generated by scripts/gen_readme.py from "
                  "geodb.errors.DATASET_REASON_CODES) -->")
DATASETS_END = "<!-- END:datasets -->"


def render():
    from geodb.client import TABLES
    lines = ["| Records lane | `export()` model | Sets | What it is |", "|---|---|---|---|"]
    for name, path, exports, sets, what in TABLES:
        export = ", ".join(f"`{e}`" for e in exports) or "—"
        lines.append(f"| `gx.{name}(project=…)` | {export} | {'`set=`' if sets else '—'} | "
                     f"{what} (`{path}`) |")
    return "\n".join([BEGIN, *lines, END])


def _meaning(cls):
    """The exception's first docstring sentence, without its code prefix."""
    doc = " ".join((cls.__doc__ or "").split())
    if doc.startswith("``") and "``:" in doc:
        doc = doc.split("``:", 1)[1].strip()
    return doc.split(". ")[0].rstrip(".").replace("``", "`").replace("|", "\\|")


def render_datasets():
    from geodb.datasets import (_RESTART_CODES, _RETRY_CODES, _RETRY_STOPS,
                                PROJECT_BUSY_RETRIES, SWITCHED_OFF_RETRIES)
    from geodb.errors import (DATASET_REASON_CODES, RECORDS_REASON_CODES, WriteForbidden,
                              WritesSwitchedOff)
    lines = ["| Reason code | Exception | Means | The client |", "|---|---|---|---|"]
    for code, cls in {**DATASET_REASON_CODES, **RECORDS_REASON_CODES}.items():
        if issubclass(cls, WritesSwitchedOff):
            does = (f"sends again at most {SWITCHED_OFF_RETRIES}×, only after a `Retry-After` "
                    "the server named (warns); else raises at once. In a write's answer it is "
                    "`DatasetWrite.stopped`")
        elif issubclass(cls, WriteForbidden):
            does = "raises; never sent again"
        elif code == "dataset_project_busy":
            does = (f"sends again {PROJECT_BUSY_RETRIES}× by default (`project_busy_retries`: "
                    "each server wait can be 30 min), warns, then raises")
        elif code in _RETRY_CODES and code in _RETRY_STOPS:
            does = ("sends again after `Retry-After` (bounded, warns) — a refused request "
                    "and a write that stopped on it alike")
        elif code in _RETRY_CODES:
            does = "sends again after `Retry-After` (bounded, warns), then raises"
        elif code in _RESTART_CODES:
            does = ("sends the same request again once (`restart_interrupted`, warns), "
                    "then raises")
        else:
            does = "raises; in a write's answer it is `DatasetWrite.stopped`"
        lines.append(f"| `{code}` | `geodb.{cls.__name__}` | {_meaning(cls)} | {does} |")
    return "\n".join([DATASETS_BEGIN, *lines, DATASETS_END])


#: name -> (begin marker, end marker, renderer)
REGIONS = {
    "tables": (BEGIN, END, render),
    "datasets": (DATASETS_BEGIN, DATASETS_END, render_datasets),
}


def _span(text, begin, end):
    a = text.index(begin)
    return a, text.index(end, a) + len(end)


def stale():
    text = README.read_text(encoding="utf-8")
    bad = []
    for name, (begin, end, renderer) in REGIONS.items():
        a, b = _span(text, begin, end)
        if text[a:b] != renderer():
            bad.append(f"the {name} region differs from its registry")
    return "; ".join(bad)


def main(argv):
    if "--check" in argv:
        problem = stale()
        print(problem or "[OK] README regions match their registries")
        return 1 if problem else 0
    text = README.read_text(encoding="utf-8")
    for begin, end, renderer in REGIONS.values():
        a, b = _span(text, begin, end)
        text = text[:a] + renderer() + text[b:]
    README.write_text(text, encoding="utf-8")
    print("wrote README.md regions: " + ", ".join(REGIONS))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
